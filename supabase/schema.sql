create table if not exists predictions (
  id             bigint generated by default as identity primary key,
  pred_date      date not null,
  stock_id       text not null,
  stock_name     text,
  score          double precision,
  rank           integer,
  raw_signal     text,          -- 模型本身的判斷：強烈買進 / 買進 / 觀望
  signal         text,          -- 加上大盤濾網後的最終建議
  market_on      boolean,
  close_at_pred  double precision,
  model_version  text,
  resolved_date  date,          -- 以下由 score.py 在 5 個交易日後回填
  actual_return  double precision,
  index_return   double precision,
  excess_return  double precision,
  hit            boolean,       -- 超額報酬 > 0
  hit_abs        boolean,       -- 絕對報酬 > 來回成本
  created_at     timestamptz default now(),
  unique (pred_date, stock_id)
);
create index if not exists predictions_pred_date_idx on predictions (pred_date desc);

create table if not exists daily_snapshot (
  pred_date      date not null,
  stock_id       text not null,
  stock_name     text,
  score          double precision,
  rank           integer,
  raw_signal     text,
  close          double precision,
  market_on      boolean,
  ret_5          double precision,
  ret_20         double precision,
  dist_ma60      double precision,
  vol_ratio      double precision,
  foreign_5      double precision,
  trust_5        double precision,
  trust_streak   integer,
  foreign_streak integer,
  margin_chg_5   double precision,
  rev_yoy        double precision,
  primary key (pred_date, stock_id)
);

create table if not exists market_status (
  date           date primary key,
  idx_close      double precision,
  idx_ma60       double precision,
  idx_ret_20     double precision,
  market_on      boolean,
  gate_enabled   boolean,
  n_signals      integer,
  model_version  text,
  updated_at     timestamptz
);

create table if not exists stats (
  id               integer primary key,
  updated_at       timestamptz,
  n_pending        integer,
  enabled          boolean,
  gate_min_n       integer,
  gate_hit_lower   double precision,
  n                integer,
  hits             integer,
  hit_rate         double precision,
  hit_rate_abs     double precision,
  hit_rate_last20  double precision,
  ci_lower         double precision,
  ci_upper         double precision,
  avg_excess       double precision,
  avg_return       double precision,
  all_n            integer,
  all_hit_rate     double precision,
  strong_n         integer,
  strong_hit_rate  double precision
);

-- 前端用 anon key 只能讀，寫入只能用 service key（排程用）
alter table predictions   enable row level security;
alter table daily_snapshot enable row level security;
alter table market_status enable row level security;
alter table stats         enable row level security;

create policy "public read predictions"    on predictions    for select using (true);
create policy "public read daily_snapshot" on daily_snapshot for select using (true);
create policy "public read market_status"  on market_status  for select using (true);
create policy "public read stats"          on stats          for select using (true);
